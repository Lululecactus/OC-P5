def sum(a, b):
    """Additionne deux nombres.

    Args:
        a (int or float): Le premier nombre.
        b (int or float): Le second nombre.

    Returns:
        int or float: La somme de a et b.
    """
    return a + b


def subtraction(a, b):
    """Soustrait un nombre d'un autre.

    Args:
        a (int or float): Le nombre duquel on soustrait.
        b (int or float): Le nombre à soustraire.

    Returns:
        int or float: Le résultat de a - b.
    """
    return a - b